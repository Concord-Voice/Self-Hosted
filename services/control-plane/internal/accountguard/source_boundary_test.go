package accountguard_test

import (
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

const sourcePackage = "github.com/Concord-Voice/Concord-Voice-Alpha/services/control-plane/internal/accountguard"

// This is a narrow dormant-reference/transaction-owner ratchet, not decide's
// purity checker or a whole-program SQL alias analysis.
func sourceBoundary(path, text string) []string {
	f, err := parser.ParseFile(token.NewFileSet(), path, text, parser.ParseComments)
	if err != nil {
		return []string{"invalid Go source"}
	}
	if ast.IsGenerated(f) || strings.HasSuffix(path, "_test.go") {
		return nil
	}
	path = filepath.ToSlash(path)
	inside := strings.HasPrefix(path, "internal/accountguard/") && !strings.HasPrefix(path, "internal/accountguard/decide/")
	aliases := map[string]bool{}
	dot := false
	for _, imp := range f.Imports {
		value, _ := strconv.Unquote(imp.Path.Value)
		if value == sourcePackage {
			name := "accountguard"
			if imp.Name != nil {
				name = imp.Name.Name
			}
			aliases[name] = true
			dot = dot || name == "."
		}
	}
	var findings []string
	var declaration *ast.Ident
	for _, decl := range f.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok && fn.Name.Name == "SourceTx" && path == "internal/accountguard/source.go" {
			declaration = fn.Name
		}
	}
	ast.Inspect(f, func(node ast.Node) bool {
		switch n := node.(type) {
		case *ast.SelectorExpr:
			if id, ok := n.X.(*ast.Ident); ok && aliases[id.Name] && n.Sel.Name == "SourceTx" {
				findings = append(findings, "external SourceTx reference")
			}
		case *ast.Ident:
			if n.Name == "SourceTx" && n != declaration && (inside || dot) {
				findings = append(findings, "unexpected SourceTx reference")
			}
		case *ast.BasicLit:
			if n.Kind == token.STRING {
				value, e := strconv.Unquote(n.Value)
				if e == nil && strings.Contains(value, "concord.auth_change_source") && path != "internal/accountguard/source.go" {
					findings = append(findings, "second source-setting owner")
				}
			}
		case *ast.CallExpr:
			if sel, ok := n.Fun.(*ast.SelectorExpr); ok && inside {
				switch sel.Sel.Name {
				case "Begin", "BeginTx", "Commit", "Rollback":
					findings = append(findings, "unexpected transaction owner")
				}
			}
		}
		return true
	})
	return findings
}
func TestSourceTxBoundaryScannerControls(t *testing.T) {
	cases := []struct {
		name, path, text string
		bad              bool
	}{
		{"alias call", "internal/users/guard.go", `package users; import ag "` + sourcePackage + `"; func f(){ag.SourceTx(nil,nil,"")}`, true},
		{"alias function escape", "internal/users/guard.go", `package users; import ag "` + sourcePackage + `"; var escape=ag.SourceTx`, true},
		{"dot escape", "internal/users/guard.go", `package users; import . "` + sourcePackage + `"; var escape=SourceTx`, true},
		{"internal call", "internal/accountguard/other.go", `package accountguard; func f(){SourceTx(nil,nil,"")}`, true},
		{"setter", "internal/users/other.go", `package users; const q="SELECT set_config('concord.auth_change_source',$1,true)"`, true},
		{"transaction opening", "internal/accountguard/other.go", `package accountguard; func f(){db.BeginTx(nil,nil)}`, true},
		{"transaction completion", "internal/accountguard/source.go", `package accountguard; func f(){tx.Commit()}`, true},
		{"rollback", "internal/accountguard/source.go", `package accountguard; func f(){tx.Rollback()}`, true},
		{"owner", "internal/accountguard/source.go", `package accountguard; func SourceTx(){tx.ExecContext(nil,"SELECT set_config('concord.auth_change_source',$1,true)")}`, false},
		{"ordinary decide", "internal/users/other.go", `package users; import d "` + sourcePackage + `/decide"; var source=d.SourceUserSession`, false},
		{"comments", "internal/users/other.go", `package users // accountguard.SourceTx and concord.auth_change_source`, false},
		{"tests", "internal/users/other_test.go", `package users; const q="concord.auth_change_source"`, false},
		{"generated", "internal/users/generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage users; const q=\"concord.auth_change_source\"", false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := sourceBoundary(c.path, c.text)
			if (len(got) > 0) != c.bad {
				t.Fatalf("unexpected scanner result: %v", got)
			}
		})
	}
}
func TestSourceTxHasOnlyItsDormantProductionOwner(t *testing.T) {
	// Like authoritycontract's source guard, anchor at Go's test working
	// directory. Compiler source filenames may be module-relative with -trimpath.
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	root := filepath.Clean(filepath.Join(wd, "..", ".."))
	sourceRoot, err := os.OpenRoot(root)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if closeErr := sourceRoot.Close(); closeErr != nil {
			t.Error(closeErr)
		}
	})
	module, err := sourceRoot.ReadFile("go.mod")
	if err != nil {
		t.Fatal(err)
	}
	moduleFields := strings.Fields(string(module))
	if len(moduleFields) < 2 || moduleFields[0] != "module" || moduleFields[1] != strings.TrimSuffix(sourcePackage, "/internal/accountguard") {
		t.Fatal("source scan must start at the control-plane module root")
	}
	err = filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			if entry.Name() == "vendor" || entry.Name() == "testdata" || strings.HasPrefix(entry.Name(), ".") {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		relative, e := filepath.Rel(root, path)
		if e != nil {
			return e
		}
		// Resolve every scanned file through the owned directory handle. This
		// confines reads even if a discovered path is replaced by a symlink.
		raw, e := sourceRoot.ReadFile(relative)
		if e != nil {
			return e
		}
		if failures := sourceBoundary(relative, string(raw)); len(failures) > 0 {
			t.Errorf("%s: %v", relative, failures)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}
